import {readFile} from 'node:fs/promises';
import {JSDOM} from 'jsdom';
import assert from 'node:assert/strict';
const folder = new URL('../Sources/AtelierUI/Resources/ChatRenderer/', import.meta.url);
const html = await readFile(new URL('index.html',folder),'utf8');
const script = await readFile(new URL('chat-renderer.js',folder),'utf8');
const dom = new JSDOM(html, {runScripts:'outside-only'});
const events = [];
dom.window.webkit = {messageHandlers:{chat:{postMessage:value=>events.push(value)}}};
dom.window.requestAnimationFrame = callback => setTimeout(callback, 0);
dom.window.cancelAnimationFrame = id => clearTimeout(id);
dom.window.ResizeObserver = class {observe() {}};
dom.window.document.fonts = {ready:Promise.resolve()};
dom.window.eval(script);
const markdown = '# Résultat\n\nDu **gras** et un [lien](https://example.com).\n\n| Région | Valeur |\n|---|---|\n| A | 2 |\n\n```python\nx = 2\nprint("été")\n```\n\nInline \\(x^2\\).\n\n\\[\\alpha = \\frac{1}{2}\\]\n\n<script>window.compromised=true</script>\n\n[x](javascript:alert(1))';
dom.window.updateMessage(markdown);
await new Promise(resolve=>setTimeout(resolve,150));
const d = dom.window.document;
assert.equal(d.querySelector('h1').textContent,'Résultat');
assert.equal(d.querySelector('strong').textContent,'gras');
assert.equal(d.querySelectorAll('table').length,1);
assert.equal(d.querySelectorAll('.katex').length,2);
assert(d.querySelector('pre .hljs-number'));
assert.equal(dom.window.compromised,undefined);
assert(!d.querySelector('a[href^="javascript:"]'));
d.querySelector('.codebar button').click();
assert(events.some(event=>event.kind==='copy' && event.text.includes('print("été")')));
const range = d.createRange(); range.selectNodeContents(d.querySelector('strong'));
dom.window.getSelection().addRange(range); d.dispatchEvent(new dom.window.Event('selectionchange'));
assert(events.some(event=>event.kind==='selection' && event.text==='gras'));
dom.window.clearSelection();
const heading = d.querySelector('h1');
const firstParagraph = d.querySelector('p');
dom.window.updateMessage(markdown + '\n\nUn mot');
await new Promise(resolve=>setTimeout(resolve,100));
assert.equal(d.querySelector('h1'),heading);
assert.equal(d.querySelector('p'),firstParagraph);
dom.window.updateMessage(markdown + '\n\nUn mot de plus');
await new Promise(resolve=>setTimeout(resolve,100));
assert.equal(d.querySelector('p'),firstParagraph);

dom.window.updateMessage('```python\nprint("unfinished")');
await new Promise(resolve=>setTimeout(resolve,100));
assert(d.querySelector('pre code').textContent.includes('unfinished'));
console.log('Rich renderer: Markdown, math, tables, code, copy, unfinished stream and HTML safety passed.');
dom.window.CSS = {highlights: new Map()};
dom.window.Highlight = class {constructor(...ranges) {this.ranges = ranges;}};
dom.window.updateMessage('La neige et la neige.');
await new Promise(resolve=>setTimeout(resolve,100));
const repeated = d.querySelector('p').firstChild;
const second = d.createRange(); second.setStart(repeated,15); second.setEnd(repeated,20);
dom.window.getSelection().addRange(second); d.dispatchEvent(new dom.window.Event('selectionchange'));
const event = events.filter(event=>event.kind==='selection').at(-1);
assert.equal(event.text,'neige'); assert.equal(event.occurrence,1); assert.equal(event.occurrences,2);
dom.window.clearSelection();
dom.window.setReadingHighlights([{id:'second',text:'neige',occurrence:1,occurrences:2}]);
assert.equal(dom.window.CSS.highlights.get('atelier-notes').ranges[0].startOffset,15);
dom.window.updateMessage('La neige et la neige. Encore.');
await new Promise(resolve=>setTimeout(resolve,100));
assert.equal(dom.window.CSS.highlights.get('atelier-notes').ranges[0].toString(),'neige');
dom.window.setReadingHighlights([{id:'hidden-comment',text:'neige',occurrence:1,occurrences:3}]);
assert.equal(dom.window.CSS.highlights.get('atelier-notes').ranges.length,0);
console.log('Reading annotations: repeated occurrence and highlight after reconciliation passed.');
const beforeResume = events.filter(event=>event.kind==='rendered').length;
dom.window.resumeRendering();
assert.equal(events.filter(event=>event.kind==='rendered').length,beforeResume);
await new Promise(resolve=>setTimeout(resolve,30));
assert.equal(events.filter(event=>event.kind==='rendered').length,beforeResume+1);
console.log('Foreground repaint acknowledges after paint frames.');
dom.window.setReadingHighlights([{id:'blue-underline',text:'neige',occurrence:1,occurrences:2,style:'underline',ink:'blue'}]);
assert.equal(dom.window.CSS.highlights.get('atelier-notes').ranges.length,0);
assert.equal(dom.window.CSS.highlights.get('atelier-underline-blue').ranges[0].startOffset,15);
dom.window.setReadingHighlights([]);
assert.equal(dom.window.CSS.highlights.get('atelier-underline-blue').ranges.length,0);
console.log('Annotation palette: independent style/color and removed ranges passed.');
dom.window.close();
