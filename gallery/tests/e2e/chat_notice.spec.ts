import {test,expect} from '@playwright/test';
import {build} from 'esbuild';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../../..');
test('chat alert line never moves the composer',async({page})=>{
 const result=await build({stdin:{contents:`import React from 'react';import {createRoot} from 'react-dom/client';import {ChatNotice} from './src/components/chat/ChatNotice';function App(){const[n,setN]=React.useState(null);window.alertOn=()=>setN({text:'effet fournisseur incertain après redémarrage',requestType:'sendReceipt',onAction:()=>setN(n=>({...n}))});window.resolveAlert=()=>setN(null);return <main><article>Le contenu de la conversation reste à sa place.</article>{n&&<ChatNotice notice={n}/>}<textarea placeholder="Écrire un message…"/></main>}createRoot(document.getElementById('root')).render(<App/>);`,resolveDir:root,loader:'tsx'},alias:{'@':path.join(root,'src')},bundle:true,write:false,outdir:'/tmp/chat-notice-test',jsx:'automatic',platform:'browser',format:'iife'});
 await page.setContent('<div id="root"></div>');
 for(const f of result.outputFiles)if(f.path.endsWith('.css'))await page.addStyleTag({content:f.text});else await page.addScriptTag({content:f.text});
 await page.addStyleTag({content:'body{background:#202327;color:#ddd;font:14px sans-serif;margin:30px}main{height:400px;display:flex;flex-direction:column}article{flex:1;min-height:0;padding-top:20px}textarea{flex:none;width:80%;height:60px}button{font:inherit}'});
 await expect(page.locator('article')).toBeVisible();
 const before=await page.locator('textarea').boundingBox();
 await page.evaluate(()=>window.alertOn());
 await expect(page.getByText('Envoi à vérifier')).toBeVisible();
 await expect(page.getByText('Ton message n’a pas été renvoyé.')).toBeVisible();
 expect((await page.locator('textarea').boundingBox()).y).toBe(before.y);
 await page.getByRole('button',{name:'Réessayer'}).click();
 await expect(page.getByText('État toujours incertain')).toBeVisible();
 await page.evaluate(()=>window.resolveAlert());
 await expect(page.locator('.chat-notice-line')).toHaveCount(0);
 expect((await page.locator('textarea').boundingBox()).y).toBe(before.y);
});
